  // Live telemetry cache populated from Open-Meteo API
  static final Map<String, WeatherData> _liveWeatherCache = {};
  static DateTime? _lastLiveFetch;

  /// Fetches real-time meteorological conditions for all cities across India
  /// via Open-Meteo's batch coordinates endpoint (1 single HTTP round-trip)
  static Future<bool> fetchLiveWeather({bool forceRefresh = false}) async {
    if (!forceRefresh &&
        _lastLiveFetch != null &&
        DateTime.now().difference(_lastLiveFetch!).inMinutes < 15 &&
        _liveWeatherCache.isNotEmpty) {
      return true;
    }

    try {
      final activeCities = cities.where((c) => c.id != 'all').toList();
      final lats = activeCities.map((c) => c.latitude.toStringAsFixed(4)).join(',');
      final lngs = activeCities.map((c) => c.longitude.toStringAsFixed(4)).join(',');
      final uri = Uri.parse(
        'https://api.open-meteo.com/v1/forecast?latitude=$lats&longitude=$lngs&current=temperature_2m,relative_humidity_2m,wind_speed_10m'
      );

      final response = await http.get(uri).timeout(const Duration(seconds: 10));
      if (response.statusCode == 200) {
        final dynamic decoded = jsonDecode(response.body);
        final List<dynamic> cityDataList = decoded is List ? decoded : [decoded];

        // Map city name to weather info
        final Map<String, Map<String, double>> cityWeather = {};
        for (int i = 0; i < activeCities.length && i < cityDataList.length; i++) {
          final current = cityDataList[i]['current'] as Map<String, dynamic>? ?? {};
          final temp = (current['temperature_2m'] as num?)?.toDouble() ?? 32.0;
          final hum = (current['relative_humidity_2m'] as num?)?.toDouble() ?? 55.0;
          final wind = (current['wind_speed_10m'] as num?)?.toDouble() ?? 5.0;
          cityWeather[activeCities[i].name] = {
            'temp': temp,
            'hum': hum,
            'wind': wind,
          };
        }

        // Distribute to all wards based on their city plus local urban microclimate variance
        final nowIso = DateTime.now().toIso8601String();
        for (final ward in wards) {
          final cInfo = cityWeather[ward.city];
          final double baseT = cInfo?['temp'] ?? _baseTempMap[ward.id] ?? 33.0;
          final double baseH = cInfo?['hum'] ?? _baseHumidityMap[ward.id] ?? 55.0;
          final double offset = _microclimateOffset[ward.id] ?? 0.0;
          final double finalTemp = double.parse((baseT + offset).toStringAsFixed(1));
          final double finalHum = baseH.clamp(15.0, 95.0);
          final double hi = HeatIndexCalculator.calculate(finalTemp, finalHum);

          _liveWeatherCache[ward.id] = WeatherData(
            wardId: ward.id,
            temperature: finalTemp,
            humidity: finalHum,
            heatIndex: double.parse(hi.toStringAsFixed(1)),
            timestamp: nowIso,
            isReal: true,
            condition: finalTemp > 40
                ? 'Severe Heat Stress'
                : (finalTemp > 35 ? 'Moderate Heat Stress' : 'Normal Thermal Range'),
          );
        }

        _lastLiveFetch = DateTime.now();
        return true;
      }
    } catch (_) {
      // Network error or timeout: fall back gracefully to calibrated baselines
    }
    return false;
  }

